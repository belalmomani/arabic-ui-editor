package com.arabicuieditor.data.github

import java.net.URLEncoder
import java.util.Base64
import org.json.JSONArray
import org.json.JSONObject

class GitHubException(message: String, val code: Int = 0) : Exception(message)

data class DeviceCode(
    val deviceCode: String,
    val userCode: String,
    val verificationUri: String,
    val intervalSec: Int,
    val expiresInSec: Int
)

sealed interface TokenPoll {
    data class Token(val token: String) : TokenPoll
    data object Pending : TokenPoll
    data object SlowDown : TokenPoll
}

data class RepoInfo(val owner: String, val name: String, val branch: String)
data class RunInfo(val id: Long, val status: String, val conclusion: String?, val url: String)

/** استدعاءات GitHub اللازمة لـ«ابنِ تطبيقي»: تسجيل الدخول بجهاز OAuth، إنشاء مستودع، رفع ملفات بـGit Data، تتبّع التشغيل. */
class GitHubApi(private val http: Http) {
    private fun enc(s: String) = URLEncoder.encode(s, "UTF-8")

    private fun auth(token: String) = mapOf(
        "Authorization" to "Bearer $token",
        "Accept" to "application/vnd.github+json",
        "X-GitHub-Api-Version" to "2022-11-28"
    )

    private fun fail(r: HttpResponse, what: String): Nothing {
        val msg = try { JSONObject(r.body).optString("message") } catch (_: Exception) { "" }
        throw GitHubException("$what (${r.code})" + if (msg.isNotEmpty()) ": $msg" else "", r.code)
    }

    // ---- تسجيل الدخول (OAuth Device Flow) ----

    fun startDeviceFlow(clientId: String): DeviceCode {
        val r = http.request(
            "POST", "https://github.com/login/device/code", mapOf("Accept" to "application/json"),
            "client_id=${enc(clientId)}&scope=${enc("repo workflow")}", Http.FORM
        )
        if (r.code != 200) fail(r, "device flow")
        val j = JSONObject(r.body)
        if (j.has("error")) throw GitHubException(j.optString("error_description", j.getString("error")))
        return DeviceCode(
            j.getString("device_code"), j.getString("user_code"), j.getString("verification_uri"),
            j.optInt("interval", 5), j.optInt("expires_in", 900)
        )
    }

    fun pollToken(clientId: String, deviceCode: String): TokenPoll {
        val r = http.request(
            "POST", "https://github.com/login/oauth/access_token", mapOf("Accept" to "application/json"),
            "client_id=${enc(clientId)}&device_code=${enc(deviceCode)}&grant_type=${enc("urn:ietf:params:oauth:grant-type:device_code")}",
            Http.FORM
        )
        if (r.code != 200) fail(r, "token")
        val j = JSONObject(r.body)
        if (j.has("access_token")) return TokenPoll.Token(j.getString("access_token"))
        return when (val e = j.optString("error")) {
            "authorization_pending" -> TokenPoll.Pending
            "slow_down" -> TokenPoll.SlowDown
            "expired_token" -> throw GitHubException("انتهت صلاحية الرمز، أعد المحاولة")
            "access_denied" -> throw GitHubException("رُفض الطلب من GitHub")
            else -> throw GitHubException(j.optString("error_description", e.ifEmpty { "خطأ غير معروف" }))
        }
    }

    // ---- المستودع والملفات ----

    fun userLogin(token: String): String {
        val r = http.request("GET", "https://api.github.com/user", auth(token))
        if (r.code != 200) fail(r, "user")
        return JSONObject(r.body).getString("login")
    }

    /** ينشئ مستودعًا خاصًا؛ إن كان موجودًا (422) يستعمله. */
    fun ensureRepo(token: String, login: String, name: String): RepoInfo {
        val body = JSONObject().put("name", name).put("private", true).put("auto_init", true)
            .put("description", "Generated by Arabic UI Editor").toString()
        val r = http.request("POST", "https://api.github.com/user/repos", auth(token), body)
        if (r.code == 201) {
            val j = JSONObject(r.body)
            return RepoInfo(login, name, j.optString("default_branch", "main"))
        }
        if (r.code == 422) {
            val g = http.request("GET", "https://api.github.com/repos/$login/$name", auth(token))
            if (g.code == 200) return RepoInfo(login, name, JSONObject(g.body).optString("default_branch", "main"))
            fail(g, "repo")
        }
        fail(r, "create repo")
    }

    /** يستبدل محتوى الفرع بالملفات كاملة في commit واحد ويعيد sha. */
    fun pushFiles(
        token: String, repo: RepoInfo, files: Map<String, ByteArray>, message: String,
        onProgress: (done: Int, total: Int) -> Unit = { _, _ -> }
    ): String {
        val base = "https://api.github.com/repos/${repo.owner}/${repo.name}"
        val ref = http.request("GET", "$base/git/ref/heads/${repo.branch}", auth(token))
        if (ref.code != 200) fail(ref, "ref")
        val parent = JSONObject(ref.body).getJSONObject("object").getString("sha")

        val tree = JSONArray()
        var done = 0
        for ((path, bytes) in files) {
            val blobBody = JSONObject().put("content", Base64.getEncoder().encodeToString(bytes)).put("encoding", "base64").toString()
            val b = http.request("POST", "$base/git/blobs", auth(token), blobBody)
            if (b.code != 201) fail(b, "blob $path")
            tree.put(JSONObject().put("path", path).put("mode", "100644").put("type", "blob").put("sha", JSONObject(b.body).getString("sha")))
            onProgress(++done, files.size)
        }
        val t = http.request("POST", "$base/git/trees", auth(token), JSONObject().put("tree", tree).toString())
        if (t.code != 201) fail(t, "tree")
        val c = http.request(
            "POST", "$base/git/commits", auth(token),
            JSONObject().put("message", message).put("tree", JSONObject(t.body).getString("sha"))
                .put("parents", JSONArray().put(parent)).toString()
        )
        if (c.code != 201) fail(c, "commit")
        val sha = JSONObject(c.body).getString("sha")
        val u = http.request(
            "PATCH", "$base/git/refs/heads/${repo.branch}", auth(token),
            JSONObject().put("sha", sha).put("force", true).toString()
        )
        if (u.code != 200) fail(u, "update ref")
        return sha
    }

    /** أول تشغيل Actions لهذا الـcommit، أو null إن لم يبدأ بعد. */
    fun runForCommit(token: String, repo: RepoInfo, sha: String): RunInfo? {
        val r = http.request(
            "GET", "https://api.github.com/repos/${repo.owner}/${repo.name}/actions/runs?head_sha=$sha&per_page=1", auth(token)
        )
        if (r.code != 200) fail(r, "runs")
        val runs = JSONObject(r.body).optJSONArray("workflow_runs") ?: return null
        if (runs.length() == 0) return null
        val j = runs.getJSONObject(0)
        return RunInfo(
            j.getLong("id"), j.optString("status"), j.optString("conclusion").takeIf { it.isNotEmpty() && it != "null" },
            j.optString("html_url")
        )
    }

    companion object {
        /** اسم مستودع: أحرف لاتينية وأرقام وشرطات، مع لاحقة من معرّف المشروع لتمييز المشاريع العربية. */
        fun repoName(projectName: String, projectId: String): String {
            val base = projectName.lowercase()
                .map { if (it in 'a'..'z' || it in '0'..'9') it else '-' }
                .joinToString("").replace(Regex("-+"), "-").trim('-').take(30)
            val suffix = projectId.filter { it.isLetterOrDigit() }.take(6).lowercase().ifEmpty { "x" }
            return (if (base.isEmpty()) "app" else base) + "-" + suffix
        }
    }
}
